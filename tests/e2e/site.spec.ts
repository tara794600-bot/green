import { test, expect } from '@playwright/test'
test('public navigation, case search, all details, and mobile menu', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '당신의 회복에, 법률로 나란히.' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/home-1440.png', fullPage: true })
  await page.getByRole('navigation', { name: '주 메뉴' }).getByRole('link', { name: '사례 안내' }).click()
  await page.getByRole('textbox', { name: '콘텐츠 검색' }).fill('미술품')
  await expect(page.locator('.article-card')).toHaveCount(1)
  await page.locator('.article-card').click()
  await expect(
    page.getByRole('heading', { name: '미술품 투자 계약의 재매입 일정이 지연된 상황' }),
  ).toBeVisible()
  const content = await (await page.request.get('/api/content')).json()
  const paths = { practice: 'practice', case: 'cases', guide: 'guides', lawyer: 'lawyers' }
  for (const a of content.articles) {
    if (a.kind === 'faq') continue
    await page.goto(`/${paths[a.kind as keyof typeof paths]}/${a.id}`)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(a.title)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: '전체 메뉴 열기' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/home-390.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '전체 메뉴 열기' }).click()
  await page.getByRole('navigation', { name: '전체 메뉴' }).getByRole('link', { name: '담당 변호사' }).click()
  await expect(page.locator('.lawyer-card')).toHaveCount(3)
  await page.goto('/consultation')
  await expect(page.getByRole('button', { name: '입력 내용 확인' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/consultation-390.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/does-not-exist')
  await expect(page.getByRole('heading', { name: '찾으시는 페이지가 없습니다.' })).toBeVisible()
  expect(errors).toEqual([])
})
